//! Typed work and resume-point vocabulary for primitive, function,
//! Promise, managed and discarded expression evaluation.
//!
//! The evaluator owns the execution loop and these are defunctionalized
//! continuations, not separately nested native evaluator calls.
use super::*;

pub(super) enum Work<'e, 'a> {
    OwnKeys(own_keys::Task<'e, 'a>),
    Managed(managed::ManagedWork<'e, 'a>),
    Eval(&'e Expression<'a>, usize, Mode),
    AwaitOperand {
        node: &'e Expression<'a>,
        depth: usize,
        mode: Mode,
        operand: awaited::Operand<'e, 'a>,
        site: Option<usize>,
    },
    Forget,
    FunctionLength(&'e Expression<'a>, usize),
    Await(&'e Expression<'a>, bool, Type, Option<usize>),
    AwaitPending(&'e Expression<'a>, Option<usize>),
    AdoptResult(&'e Expression<'a>),
    LiftAsyncValue(&'e Expression<'a>),
    AwaitAsyncValue(&'e Expression<'a>, usize),
    ConsumeAsyncValue(&'e Expression<'a>, Mode),
    PendingTruthy(&'e Expression<'a>),
    AwaitSettled(&'e Expression<'a>, Option<usize>),
    FulfillPromise(&'e Expression<'a>),
    CreatePromise(&'e Expression<'a>, bool),
    PromotePromise(&'e Expression<'a>),
    PromiseValue(&'e Expression<'a>),
    PromiseTruthy(&'e Expression<'a>),
    FinishAwaitCall(&'e Expression<'a>, Type, Option<usize>),
    VoidResult(&'e Expression<'a>),
    Pack(&'e Expression<'a>),
    Convert(&'e Expression<'a>),
    Truthy(&'e Expression<'a>),
    GeneralTruthy(&'e Expression<'a>),
    NumberFromGeneral(&'e Expression<'a>),
    NumberFromAsyncValue(&'e Expression<'a>),
    Not(&'e Expression<'a>),
    Unary(&'e Expression<'a>, Unary),
    BinaryRight {
        node: &'e Expression<'a>,
        right: &'e Expression<'a>,
        depth: usize,
        mode: Mode,
        operator: Binary,
    },
    Binary {
        node: &'e Expression<'a>,
        left: ValueId,
        operator: Binary,
    },
    PrimitiveCompareRight {
        node: &'e Expression<'a>,
        right: &'e Expression<'a>,
        depth: usize,
        loose: bool,
        negated: bool,
    },
    SelectionCompareRight {
        node: &'e Expression<'a>,
        right: &'e Expression<'a>,
        depth: usize,
        loose: bool,
        negated: bool,
    },
    SelectionCompare {
        node: &'e Expression<'a>,
        left: ValueId,
        loose: bool,
        negated: bool,
    },
    PromiseCompareRight {
        node: &'e Expression<'a>,
        right: &'e Expression<'a>,
        depth: usize,
        left_promise: bool,
        right_promise: bool,
        negated: bool,
    },
    PromiseCompare {
        node: &'e Expression<'a>,
        left: ValueId,
        left_promise: bool,
        right_promise: bool,
        negated: bool,
    },
    PrimitiveCompare {
        node: &'e Expression<'a>,
        left: ValueId,
        loose: bool,
        negated: bool,
    },
    RelationalRight {
        node: &'e Expression<'a>,
        right: &'e Expression<'a>,
        depth: usize,
        operator: Relational,
        mode: Mode,
    },
    Relational {
        node: &'e Expression<'a>,
        left: ValueId,
        operator: Relational,
    },
    CompareRight {
        node: &'e Expression<'a>,
        right: &'e Expression<'a>,
        depth: usize,
        booleans: bool,
        operator: Compare,
    },
    Compare {
        node: &'e Expression<'a>,
        left: ValueId,
        operator: Compare,
    },
    LogicalAssign {
        node: &'e Expression<'a>,
        assignment: &'e oxc_ast::ast::AssignmentExpression<'a>,
        slot: SlotId,
        old: ValueId,
        condition: ValueId,
    },
    StoreGeneral {
        node: &'e Expression<'a>,
        slot: SlotId,
    },
    StoreTyped {
        node: &'e Expression<'a>,
        slot: SlotId,
    },
    Assign {
        node: &'e Expression<'a>,
        slot: SlotId,
        previous: Option<ValueId>,
        operator: Option<Binary>,
    },
    Call {
        node: &'e Expression<'a>,
        call: &'e CallExpression<'a>,
        function: ir::FunctionId,
        index: usize,
        arguments: Vec<ValueId>,
        depth: usize,
    },
    UiCall {
        node: &'e Expression<'a>,
        call: &'e CallExpression<'a>,
        index: usize,
        arguments: Vec<ValueId>,
        depth: usize,
    },
    MathCall {
        node: &'e Expression<'a>,
        call: &'e CallExpression<'a>,
        operator: Unary,
        index: usize,
        input: Option<ValueId>,
        depth: usize,
    },
    LocalCall {
        node: &'e Expression<'a>,
        call: &'e CallExpression<'a>,
        closure: closures::LocalClosure,
        index: usize,
        arguments: Vec<ValueId>,
        depth: usize,
        site: Option<usize>,
    },
    ClosureCall {
        node: &'e Expression<'a>,
        call: &'e CallExpression<'a>,
        callee: ValueId,
        effect: ClosureEffect,
        index: usize,
        arguments: Vec<ValueId>,
        depth: usize,
        site: Option<usize>,
    },
    BeginAwaitedClosureCall {
        node: &'e Expression<'a>,
        call: &'e CallExpression<'a>,
        signature: usize,
        depth: usize,
        site: Option<usize>,
    },
    RestoreBindings(Vec<NumericBinding>, bool),
    Sequence {
        remaining: &'e [Expression<'a>],
        last: &'e Expression<'a>,
        depth: usize,
        mode: Mode,
    },
    Condition {
        node: &'e Expression<'a>,
        consequent: &'e Expression<'a>,
        alternate: &'e Expression<'a>,
        depth: usize,
        mode: Mode,
    },
    Consequent {
        node: &'e Expression<'a>,
        condition: ValueId,
        alternate: &'e Expression<'a>,
        depth: usize,
        mode: Mode,
    },
    Alternate {
        node: &'e Expression<'a>,
        condition: ValueId,
        consequent: Region,
        mode: Mode,
    },
    LogicalLeft {
        node: &'e Expression<'a>,
        left: &'e Expression<'a>,
        right: &'e Expression<'a>,
        operator: LogicalOperator,
        depth: usize,
        mode: Mode,
    },
    LogicalRight {
        node: &'e Expression<'a>,
        left_node: &'e Expression<'a>,
        left: Value,
        condition: ValueId,
        operator: LogicalOperator,
        mode: Mode,
    },
}
